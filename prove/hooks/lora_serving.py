"""Route OpenAI-HTTP requests to the adapter being trained (verl 0.8 + vLLM 0.22, LoRA mode).

verl keeps the trained adapter in vLLM under its own LoRA name and attaches it only on its token-in/token-out
generation path. Agent Lightning sends rollouts to vLLM's OpenAI endpoint with the base model's name, and vLLM
attaches a LoRA only when the request names one known to the HTTP layer. Without this hook every rollout and
every validation episode is generated by the base model while the trainer updates the adapter.

Here a request that resolves to the base model gets verl's adapter. verl syncs the adapter in every weight
update, including the initial one before the first rollout, so it is always loaded when requests arrive.
"""
from __future__ import annotations

from prove.hooks._post_import import patch_after_import

_MODULE = "vllm.entrypoints.openai.engine.serving"
_count = 0


def _patch(module) -> None:  # noqa: ANN001
    cls = getattr(module, "OpenAIServing", None)
    if cls is None or getattr(cls._maybe_get_adapters, "_prove", False):
        return
    original = cls._maybe_get_adapters

    def _maybe_get_adapters(self, request, supports_default_mm_loras: bool = False):  # noqa: ANN001
        lora = original(self, request, supports_default_mm_loras)
        if lora is not None:
            return lora
        from vllm.lora.request import LoRARequest

        from verl.workers.rollout.vllm_rollout.utils import VLLM_LORA_INT_ID, VLLM_LORA_NAME, VLLM_LORA_PATH

        global _count
        _count += 1
        if _count in (1, 10, 100, 1000) or _count % 10000 == 0:
            print(f"[prove] HTTP request #{_count} model={request.model!r} -> trained adapter "
                  f"{VLLM_LORA_NAME}/{VLLM_LORA_INT_ID}", flush=True)
        return LoRARequest(lora_name=VLLM_LORA_NAME, lora_int_id=VLLM_LORA_INT_ID, lora_path=VLLM_LORA_PATH)

    _maybe_get_adapters._prove = True
    cls._maybe_get_adapters = _maybe_get_adapters
    print(f"[prove] {_MODULE}.OpenAIServing routes base-model requests to the trained adapter", flush=True)


def apply() -> None:
    patch_after_import("lora_serving", {_MODULE: _patch})
